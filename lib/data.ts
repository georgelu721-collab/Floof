/** Clan war ends at the next Sunday 8pm (local), so the countdown always feels alive. */
export function clanWarEnd(now = new Date()) {
  const end = new Date(now);
  const day = end.getDay();
  const add = (7 - day) % 7 || (end.getHours() >= 20 ? 7 : 0);
  end.setDate(end.getDate() + add);
  end.setHours(20, 0, 0, 0);
  if (end.getTime() - now.getTime() < 36 * 3600_000) end.setDate(end.getDate() + 7);
  return end;
}

export const petById = (id: string, pets: Pet[] = PETS) => pets.find((p) => p.id === id);
export const petByHandle = (h: string, pets: Pet[] = PETS) => pets.find((p) => p.handle === h);

export function compact(n: number) {
  if (n >= 1_000_000) return `${(n / 1_000_000).toFixed(1).replace(/\.0$/, "")}M`;
  if (n >= 10_000) return `${(n / 1000).toFixed(1).replace(/\.0$/, "")}K`;
  if (n >= 1000) return `${(n / 1000).toFixed(1).replace(/\.0$/, "")}K`;
  return `${n}`;
}

export function timeAgo(ms: number, now = Date.now()) {
  const s = Math.max(1, Math.floor((now - ms) / 1000));
  if (s < 60) return "now";
  const m = Math.floor(s / 60);
  if (m < 60) return `${m}m`;
  const h = Math.floor(m / 60);
  if (h < 24) return `${h}h`;
  const d = Math.floor(h / 24);
  if (d < 7) return `${d}d`;
  return `${Math.floor(d / 7)}w`;
}
